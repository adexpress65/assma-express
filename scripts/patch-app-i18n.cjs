function patchFile(name, appBlock) {
  const fp = path.join(dir, name);
  let raw = strip(fs.readFileSync(fp, "utf8"));
  const data = JSON.parse(raw);
  if (data.app) {
    console.log(name, "already has app, merge");
  }
  data.app = { ...(data.app || {}), ...appBlock };
  fs.writeFileSync(fp, JSON.stringify(data, null, 2) + "\n", "utf8");
  console.log("patched", name);
}

